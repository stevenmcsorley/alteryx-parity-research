#!/usr/bin/env python3
"""Produce a factual coverage report from data/tool-status.json. Never implies parity."""
from __future__ import annotations

import json
from collections import Counter, defaultdict

from catalog_lib import ROOT, CATALOG


def report():
    rows = json.loads(CATALOG.read_text(encoding='utf-8'))['tools']
    meta = json.loads(CATALOG.read_text(encoding='utf-8'))['metadata']
    status = json.loads((ROOT / 'data' / 'tool-status.json').read_text(encoding='utf-8'))
    t = status['totals']
    ledger = status['tools']
    bycat = defaultdict(Counter)
    for l in ledger:
        c = bycat[l['category']]
        c['entries'] += 1
        c['implemented'] += l['implementation_status'] == 'implemented'
        c['ref_partial'] += l['verification_status'] == 'partial'
        c['anchors'] += l['anchors_known']
        c['blocking'] += l['external_prerequisites_blocking']
    impl_rows = [l for l in ledger if l['kernel']]
    lines = [
        '# Research, implementation and conformance status',
        '',
        '> Generated by `scripts/coverage_report.py` from `data/tool-status.json` (itself derived from evidence by '
        '`scripts/build_status.py`). **Catalogue entries are not implemented tools, and "partial" reference '
        'verification is not a parity claim.**',
        '',
        '## Headline metrics (reported separately, never combined)',
        '',
        '| Axis | Count |',
        '|---|---:|',
        f'| Public catalogue entries (category occurrences) | {len(rows)} |',
        f'| Distinct tool names | {len(set(r["name"] for r in rows))} |',
        f'| Public help URL resolved (official tool list sync) | {sum(bool(r.get("documentation_url")) for r in rows)} |',
        f'| Machine-readable contracts generated | {t["catalogue_entries"]} |',
        f'| Entries with known anchors (manifest, reference-observed or public-doc) | {t["anchors_known"]} |',
        f'| Entries observed in authorised reference workflows (structure only) | {t["reference_observed"]} |',
        f'| Independent kernels implemented and passing tests | {t["implementation_status"].get("implemented", 0)} |',
        f'| Entries with differential reference cases, all passing ("partial") | {t["verification_status"].get("partial", 0)} |',
        f'| Entries with failing reference cases | {t["verification_status"].get("failed", 0)} |',
        f'| Reference cases passed / run | {t["conformance_cases_passed"]} / {t["conformance_cases"]} |',
        f'| Entries whose exact behaviour needs licensed data/services (blocked until authorised access) | {t["external_prerequisites_blocking"]} |',
        f'| Entries fully verified against the reference | {t["verification_status"].get("verified", 0)} |',
        f'| Unit/integration tests in last ledger build | {status["test_run"]["tests_run"]} run, {status["test_run"]["tests_failed"]} failed |',
        '',
        f'Catalogue source retrieved {meta.get("source_retrieved_at_utc", "unknown")} (sha256 '
        f'`{str(meta.get("source_sha256"))[:16]}…`). Conformance reference build(s): '
        f'{", ".join(status["conformance_builds"]) or "none"}.',
        '',
        '## Implemented kernels',
        '',
        '| Catalogue id | Kernel | Tests | Reference cases (passed/run) | Verification |',
        '|---|---|---:|---:|---|',
        *[f'| `{l["id"]}` | `{l["kernel"]}` | {l["independent_tests"]} | {l["conformance_passed"]}/{l["conformance_cases"]} '
          f'| {l["verification_status"]} |' for l in impl_rows],
        '',
        '## By category',
        '',
        '| Category | Entries | Kernels | Ref-partial | Anchors known | Blocked by external prerequisites |',
        '|---|---:|---:|---:|---:|---:|',
        *[f'| {cat} | {c["entries"]} | {c["implemented"]} | {c["ref_partial"]} | {c["anchors"]} | {c["blocking"]} |'
          for cat, c in sorted(bycat.items())],
        '',
        '## Interpretation',
        '',
        '- "Implemented" means an original kernel runs real data and passes this repository\'s tests. It does not '
        'mean every configuration option of the reference tool is supported; unsupported options are absent from '
        'the kernel\'s config schema and are rejected at validation.',
        '- "Partial" verification means every recorded differential case passed against the stated reference '
        'build, engine and settings. Coverage of the tool\'s option space is listed per case in the contract JSON.',
        '- Entries without a kernel fail validation with `tool-unavailable`; nothing is stubbed.',
        '- See docs/TOOL_STATUS_RULES.md, docs/CONFORMANCE.md and docs/AUTHORISATION.md.',
    ]
    return '\n'.join(lines) + '\n'


def main():
    dest = ROOT / 'docs' / 'COVERAGE.md'
    dest.write_text(report(), encoding='utf-8')
    print(f'Wrote {dest}')


if __name__ == '__main__':
    main()
